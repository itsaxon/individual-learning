-- ============================================================
-- 找出冒牌货：词对表
-- 每行存储一对「近似词」：word_a 与 word_b 语义接近但不相同
-- 开局时由领域服务随机决定哪个词给平民、哪个给冒牌货
-- 支持最多 8 人同房（平民共享一词，冒牌货拿另一词）
-- ============================================================

CREATE TABLE IF NOT EXISTS `impostor_word_pair` (
    `id`          BIGINT       NOT NULL                 COMMENT '主键(雪花ID,领域预生成)',
    `word_a`      VARCHAR(32)  NOT NULL                 COMMENT '近似词 A',
    `word_b`      VARCHAR(32)  NOT NULL                 COMMENT '近似词 B',
    `category`    VARCHAR(32)  NOT NULL DEFAULT '通用'  COMMENT '分类(食物/地点/交通/器物/活动...)',
    `deleted`     TINYINT      NOT NULL DEFAULT 0       COMMENT '逻辑删除:0未删 1已删',
    `creator`     BIGINT       NOT NULL DEFAULT 0       COMMENT '创建人ID',
    `updater`     BIGINT       NOT NULL DEFAULT 0       COMMENT '更新人ID',
    `create_time` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP                            COMMENT '创建时间',
    `update_time` DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_word_pair` (`word_a`, `word_b`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='冒牌货词对表';

